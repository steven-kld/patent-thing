-- Сверка снимков publications ДО выбора vintage.
-- Дало: в окне 2013-2017 между 202105, 202511 и живой расходятся
--       2 строки из 3 506 574 (0,00006%); 202511 и живая совпадают до единицы.
--       Расхождения: 2015 B2 +1, 2016 A2 -1, 2016 S -2, 2017 A1 +4,
--       2017 A2 -1, 2017 B2 +1; сальдо +2 сходится с разницей итогов.
-- Вывод: выбор снимка на числа воронки не влияет; решать надо по
-- воспроизводимости и цене. Manifest §7 «Vintage».
-- ОГРАНИЧЕНИЕ ВЫБОРА: в снимках до 202105 нет поля parent — критерий 4
-- на них невыразим.
-- НЕ ПРОВЕРЕНО: заполненность description_localized между снимками.
-- Цена: 1,90 + 2,39 + 2,44 = 6,73 ГиБ.
-- --maximum_bytes_billed=2900000000

-- запускать по одному разу на каждую таблицу, подставляя имя:
--   publications_202105 | publications_202511 | publications
SELECT DIV(publication_date,10000) y, kind_code, COUNT(*) c
FROM `patents-public-data.patents.publications_202511`
WHERE country_code='US' AND publication_date BETWEEN 20130101 AND 20171231
GROUP BY 1,2 ORDER BY 1,2;
