-- Покрытие источника метки помесячно: art unit 21xx и весь источник.
-- Дало устойчивую полосу 2014-01 … 2017-02 и рваный хвост:
--   2017-01 4 327 | 2017-02 3 923 | 2017-03 525 | 2017-04 2 | 2017-05 58
--   | 2017-06 4 566 | 2017-07 694   (по 21xx, все действия)
-- Провал идёт по ВСЕМУ источнику (апрель 2017: 93 действия на весь USPTO),
-- а неполные месяцы смещены по составу: доля 21xx в них 2,2-5,9% против
-- устойчивых 7,8-9,1%. Основание правой границы окна. Manifest §7 «Покрытие».
-- Цена: 120 МБ.
-- --maximum_bytes_billed=120000000

SELECT SUBSTR(mail_dt,1,7) ym,
       COUNTIF(SUBSTR(art_unit,1,2)='21') c21,
       COUNT(*) call
FROM `patents-public-data.uspto_oce_office_actions.office_actions` WHERE mail_dt >= '2012-01'
GROUP BY 1 ORDER BY 1;
