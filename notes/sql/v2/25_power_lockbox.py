#!/usr/bin/env python3
"""ШАГ 19. Мощность на фактических N. Страт = 1: вердикт на ящике целиком.

Всё выражено в единицах правила решения — EV в долларах. Точность в правиле
не участвует и здесь не назначается: она входит только в дисперсию ставки.

Запросом не является — локальный пересчёт из замороженных констант Proposal
и фактического размера ящика после purge (шаг 17). Денег не стоит.
Запуск: python3 notes/sql/v2/25_power_lockbox.py

Ставка: +c_win при верной, -c_loss при ошибочной, 0 при пасе.
  X_i = +10 с вероятностью p, -80 с вероятностью 1-p
  E[X]  = 90p - 80                       (= EV на ставку, USD)
  SD[X] = 90 * sqrt(p(1-p))              (размах 10-(-80) = 90)
При n независимых ставках EV = n(90p-80), SD = 90*sqrt(n*p(1-p)).
Нижняя односторонняя граница уровня L: EV - z*SD.

Независимость ставок — допущение этого расчёта, а не факт. Братские заявки
дают положительную корреляцию исходов, и тогда SD занижена, а требуемая p
занижена вместе с ней. Мера зависимости измеряется отдельно (E13).
"""
from statistics import NormalDist

C_WIN, C_LOSS, C_TARGET = 10.0, 80.0, 1650.0
BOX = 7405                      # 2016H2 после purge: 7417 - 12
LEVEL = 0.95
z = NormalDist().inv_cdf(LEVEL)

ev   = lambda p: (C_WIN + C_LOSS) * p - C_LOSS
sd1  = lambda p: (C_WIN + C_LOSS) * (p * (1 - p)) ** 0.5
p_be = C_LOSS / (C_WIN + C_LOSS)

print(f"безубыточность p* = {p_be:.6f}")
print(f"ящик = {BOX};  c_target = {C_TARGET:g} USD;  z({LEVEL}) = {z:.4f}")
print(f"плотность цели = {C_TARGET/BOX:.6f} USD/заявка\n")

print("A. ЁМКОСТЬ: сколько ставок нужно, чтобы ТОЧЕЧНЫЙ EV дотянул до 1650")
print(f"{'EV/ставку':>10} {'n_min':>9} {'% ящика':>9}")
for e in (0.10, 0.25, 0.50, 1.0, 2.0, 3.0, 4.0, 5.5, 8.0, 10.0):
    n = C_TARGET / e
    mark = "" if n <= BOX else "  ← не влезает в ящик"
    print(f"{e:10.2f} {n:9.1f} {100*n/BOX:8.2f}%{mark}")
print(f"\nпол ёмкости: EV/ставку >= {C_TARGET/BOX:.4f} USD — и ставить на весь ящик")

print("\nB. ЦЕНА ИНТЕРВАЛА: какой ТОЧЕЧНЫЙ EV нужен, чтобы ci_low дотянул до 1650")
print(f"{'ставок':>8} {'% ящика':>9} {'SD(EV)':>9} {'нужен EV':>10} {'сверх 1650':>11}")
def frontier(n):
    """EV точечный на границе ci_low = c_target при n ставках."""
    lo, hi = p_be, 1.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if n * ev(mid) - z * sd1(mid) * n ** 0.5 >= C_TARGET:
            hi = mid
        else:
            lo = mid
    return n * ev(hi), z * sd1(hi) * n ** 0.5 / z
for n in (300, 500, 1000, 1051, 2000, 3000, 5000, BOX):
    e, sd = frontier(n)
    print(f"{n:8d} {100*n/BOX:8.2f}% {sd:9.1f} {e:10.1f} {100*(e/C_TARGET-1):10.0f}%")

print("\nЧитается так: правило стоит на нижней границе интервала (P10), поэтому")
print("точечный EV обязан превышать 1650 на ширину интервала. Чем больше ставок,")
print("тем шире интервал и тем выше требуемый точечный EV. Точность здесь не")
print("назначается и не объявляется — она лишь параметр, через который считается")
print("дисперсия ставки; правило решения её не содержит.")
