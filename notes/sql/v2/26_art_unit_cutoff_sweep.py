#!/usr/bin/env python3
"""Перепроверка: даёт ли отказ от «плохих» art unit положительный EV на ящике.

УСТАРЕЛО в части чисел: здесь состав ящика оценён масштабированием
train+valid, что дало 1 284. Точный расчёт на фактическом составе —
26_art_unit_box_composition.csv, он даёт 1 179. Вне выборки то же самое
проверено в 27_art_unit_walkforward.py.

Запросом не является — развёртка уже измеренного (18_art_unit_rates.sql,
train+valid 2015-01…2016-06, 69 подразделений, 23 560 заявок, доля 76,45%).
Новых денег не стоит. Запуск: python3 notes/sql/v2/26_art_unit_cutoff_sweep.py

Вопрос автора дословно: «есть ли статистическая выгода в снижении объема
датасета, выкидывая из него такие случаи, где 103 встречается реже обычного?
я бы просто на "плохих" всегда пасовал и все».

Правило пасовать на подразделениях ниже порога — это чистый фильтр без модели.
Считается в единицах правила решения: EV = n * (90p - 80), цель 1650 USD.
"""
C_WIN, C_LOSS, C_TARGET = 10.0, 80.0, 1650.0
N_TV, BOX = 23560, 7405
SCALE = BOX / N_TV                      # доля ящика от train+valid по объёму
ev = lambda p: (C_WIN + C_LOSS) * p - C_LOSS
p_be = C_LOSS / (C_WIN + C_LOSS)

# корзины из шапки 18_art_unit_rates.sql, от высокой доли к низкой
BUCKETS = [                 # (нижняя граница, units, n, доля)
    (0.95,  0,     0, None),
    (0.90,  4, 1232, 0.925),
    (0.8889, 1,  175, 0.894),          # одна страта в 88,89–90%, взята серединой
    (0.85,  9, 3162, 0.870),
    (0.80, 16, 6012, 0.826),
    (0.00, 39, 12979, 0.693),
]

print(f"безубыточность p* = {p_be:.4f};  цель {C_TARGET:g} USD;  ящик {BOX}")
print(f"масштаб train+valid → ящик: {SCALE:.5f}\n")
print(f"{'порог':>8} {'страт':>6} {'n (18мес)':>10} {'доля':>7} {'EV/ставку':>10}"
      f" {'n на ящике':>11} {'EV на ящике':>12}")

n_cum = w_cum = u_cum = 0
for lo, units, n, rate in BUCKETS:
    if n:
        n_cum += n; w_cum += n * rate; u_cum += units
    if lo == 0.00:
        label = "без фильтра"
    else:
        label = f">= {lo:.4f}".rstrip("0").rstrip(".")
    p = w_cum / n_cum if n_cum else 0.0
    e = ev(p)
    n_box = n_cum * SCALE
    print(f"{label:>8} {u_cum:6d} {n_cum:10d} {p:7.4f} {e:10.2f}"
          f" {n_box:11.0f} {n_box*e:12.0f}")

print("\nтребуется на ящике:")
print(f"  точечный EV >= {C_TARGET:g}")
print("  а по правилу ci_low(EV) >= 1650 точечный EV обязан быть ещё выше:")
print("  2108 при 300 ставках, 2420 при 500 (25_power_lockbox.py)")
