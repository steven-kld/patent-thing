-- ШАГ 17. Список purge: строки, попавшие в группы точного совпадения
-- title+abstract через шов 2016-06-30. Обе стороны каждой пары.
-- Критерий объявлен ДО запечатывания Lockbox; разрывы номеров заявок и длины
-- рефератов в критерий НЕ входят — решение автора.
--
-- Дало: 12 групп, 26 строк.
--   2015H1 (трейн)      2 строки   13859613 13918690
--   2015H2 (W1)         0 строк
--   2016H1 (W2)        12 строк
--   2016H2 (ящик)      12 строк
-- Окна после purge: 9 522 / 6 523 / 7 501 / 7 405.
--
-- Подпись механизма видна по номерам: в 8 из 12 групп они идут подряд
-- (14280629/14280630/14280631), то есть серия заявок одного заявителя
-- с общим заголовком и рефератом. Критерий 4 (parent пуст) их не снял:
-- братские заявки родство через parent не объявляют.
-- В 4 группах номера далёкие (14297909 ↔ 14896656) — значит соседство
-- номеров необходимым условием не является и критерием служить не может.
--
-- Цена: ~24 МиБ. --maximum_bytes_billed=100000000

WITH n AS (
  SELECT app_id, period, first_action_date,
         TO_HEX(MD5(CONCAT(
           LOWER(REGEXP_REPLACE(IFNULL(title,''),    r'\s+', ' ')), ' ||| ',
           LOWER(REGEXP_REPLACE(IFNULL(abstract,''), r'\s+', ' '))))) h
  FROM `<свой проект>.patent_v2.cohort`
),
g AS (
  SELECT h FROM n GROUP BY 1
  HAVING COUNTIF(period='2016H2') > 0 AND COUNTIF(period!='2016H2') > 0
)
SELECT n.h, n.app_id, n.period, n.first_action_date
FROM n JOIN g USING (h)
ORDER BY n.h, n.first_action_date;
